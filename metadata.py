"""Prepare local Formula 1 metadata before a video is published to Plex."""

from datetime import date
from pathlib import Path
import os
import re
import tempfile
import xml.etree.ElementTree as ET

from permissions import apply_permissions

MARKER = b'<!-- Generated by FolderSync -->'
DEFAULT_DESCRIPTION = (
    "Formula 1 Grand Prix weekend coverage, following drivers and teams as they compete "
    "for the Drivers' and Constructors' championships at circuits around the world. "
    "The collection includes practice, qualifying, sprint sessions and races when available. "
    "Explore each Grand Prix weekend from the opening practice sessions through "
    "the battle for pole position and the race to the chequered flag."
)


def validate_config(config):
    if not isinstance(config, dict):
        raise ValueError("metadata must be an object")
    for key in ("title", "description", "poster", "background"):
        if key in config and (not isinstance(config[key], str) or not config[key].strip()):
            raise ValueError(f"metadata.{key} must be nonempty text")
    genres = config.get("genres", ["Sports", "Motorsport"])
    if not isinstance(genres, list) or not genres or any(not isinstance(g, str) or not g.strip() for g in genres):
        raise ValueError("metadata.genres must be a nonempty list of text")
    events = config.get("events", {})
    if not isinstance(events, dict):
        raise ValueError("metadata.events must be an object")
    for code, event in events.items():
        if not isinstance(code, str) or len(code) != 4 or not code.isascii() or not code.isdigit() or not isinstance(event, dict):
            raise ValueError("metadata.events must map YYRR season codes to objects")
        for key in ("name", "description", "poster"):
            if key in event and (not isinstance(event[key], str) or not event[key].strip()):
                raise ValueError(f"metadata.events.{code}.{key} must be nonempty text")
        sessions = event.get("sessions", {})
        if not isinstance(sessions, dict):
            raise ValueError("metadata event sessions must be an object")
        for session, values in sessions.items():
            if not isinstance(session, str) or not isinstance(values, dict):
                raise ValueError("metadata sessions must map session names to objects")
            for key in ("title", "description", "date"):
                if key in values and (not isinstance(values[key], str) or not values[key].strip()):
                    raise ValueError(f"metadata session {key} must be nonempty text")
            if "date" in values:
                parsed = date.fromisoformat(values["date"])
                if parsed.isoformat() != values["date"] or parsed.year != 2000 + int(code[:2]):
                    raise ValueError("metadata session date must be YYYY-MM-DD in the event year")


def write_xml(path, root, *, update=False, replace_content=None):
    """Publish complete XML atomically; keep user-authored NFO files."""
    if os.path.lexists(path):
        if path.is_symlink() or not update:
            return "existing"
        existing = path.read_bytes()
        if MARKER not in existing and existing != replace_content:
            return "existing"
    content = b'<?xml version="1.0" encoding="UTF-8"?>\n' + MARKER + b'\n' + ET.tostring(root, encoding="utf-8") + b'\n'
    if path.exists() and path.read_bytes() == content:
        return "existing"
    with tempfile.NamedTemporaryFile(dir=path.parent, prefix=".metadata-", delete=False) as stream:
        temporary = Path(stream.name)
        stream.write(content)
    try:
        apply_permissions(temporary)
        if update and path.exists():
            os.replace(temporary, path)
        else:
            try:
                os.link(temporary, path)
            except FileExistsError:
                return "existing"
    finally:
        temporary.unlink(missing_ok=True)
    return "created"


def copy_art(show, source, target):
    """Read selected artwork inside the show folder; preserve existing assets."""
    source = Path(source)
    if source.is_absolute() or ".." in source.parts:
        raise ValueError("Metadata artwork paths must be relative to the Formula 1 show folder")
    source = (show / source).resolve(strict=True)
    if not source.is_relative_to(show.resolve()) or source.suffix.lower() not in (".jpg", ".jpeg", ".png"):
        raise ValueError("Metadata artwork must be a local JPEG or PNG inside the show folder")
    from PIL import Image
    with Image.open(source) as image:
        image.verify()
    target = target.with_suffix(source.suffix.lower())
    if not any(os.path.lexists(target.with_suffix(ext)) for ext in (".jpg", ".jpeg", ".png")):
        with tempfile.NamedTemporaryFile(dir=target.parent, prefix=".artwork-", delete=False) as stream:
            temporary = Path(stream.name)
            stream.write(source.read_bytes())
        try:
            apply_permissions(temporary)
            try:
                os.link(temporary, target)
            except FileExistsError:
                pass
        finally:
            temporary.unlink(missing_ok=True)


def prepare_artwork(directory, f1, config):
    show = directory.parent
    event = config.get("events", {}).get(f1.code, {})
    for source, target in ((config.get("poster"), show / "poster"),
                           (config.get("background"), show / "background"),
                           (event.get("poster"), directory / f"Season{f1.code}")):
        if source:
            copy_art(show, source, target)


def season_year(code):
    """Decode a YYRR code, including Plex's integer form with leading zeros omitted."""
    if not re.fullmatch(r"[0-9]{1,4}", code):
        return None
    code = code.zfill(4)
    if not 1 <= int(code[2:]) <= 26:
        return None
    return 2000 + int(code[:2])


def prepare_show(show, config, *, season_code=None, season_name=None, rebuild=False):
    show_path = show / "tvshow.nfo"
    root = ET.Element("tvshow")
    if show_path.exists() and not show_path.is_symlink() and MARKER in show_path.read_bytes():
        try:
            root = ET.parse(show_path).getroot()
        except ET.ParseError:
            if not rebuild:
                raise
    for tag, value in (("title", config.get("title", "Formula 1")),
                       ("plot", config.get("description", DEFAULT_DESCRIPTION))):
        for old in list(root.findall(tag)):
            root.remove(old)
        ET.SubElement(root, tag).text = value
    for old in list(root.findall("genre")):
        root.remove(old)
    for genre in config.get("genres", ["Sports", "Motorsport"]):
        ET.SubElement(root, "genre").text = genre
    if season_code is not None:
        for old in list(root.findall("namedseason")):
            if old.get("number") == str(int(season_code)):
                root.remove(old)
        ET.SubElement(root, "namedseason", number=str(int(season_code))).text = season_name
    codes = [item.get("number", "") for item in root.findall("namedseason")]
    from nfo import VIDEO_EXTENSIONS, parse_episode
    for folder in show.iterdir():
        match = re.fullmatch(r"Season ([0-9]{4})", folder.name)
        if match and folder.is_dir() and not folder.is_symlink():
            # An old calendar-year folder such as Season 2026 is ambiguous.
            # Count it only when an episode actually uses that YYRR season.
            for video in folder.iterdir():
                if video.suffix.lower() not in VIDEO_EXTENSIONS or video.is_symlink() or not video.is_file():
                    continue
                episode = parse_episode(video)
                if episode is not None and episode[0] == int(match[1]):
                    codes.append(match[1])
                    break
    years = [year for code in codes if (year := season_year(code)) is not None]
    if years:
        first_year = min(years)
        # Plex reads premiered, rather than a bare year, for series dates.
        # January 1 is a collection-year convention, not an actual session date.
        for tag, value in (("year", str(first_year)), ("premiered", f"{first_year}-01-01")):
            for old in list(root.findall(tag)):
                root.remove(old)
            ET.SubElement(root, tag).text = value
    return write_xml(show_path, root, update=True)


def refresh_generated_shows(directory, config, report_error):
    """Backfill owned show metadata even when original source videos are gone."""
    errors = 0
    def failed(error):
        nonlocal errors
        errors += 1
        report_error(f"ERROR Cannot update show metadata: {error}")
    for parent, _, files in os.walk(directory, followlinks=False, onerror=failed):
        if "tvshow.nfo" not in files:
            continue
        path = Path(parent) / "tvshow.nfo"
        try:
            if not path.is_symlink() and MARKER in path.read_bytes():
                prepare_show(path.parent, config)
        except (OSError, ValueError, ET.ParseError) as error:
            failed(error)
    return errors


def prepare_season(directory, f1, year, config, *, rebuild=False):
    event = config.get("events", {}).get(f1.code, {})
    name = event.get("name", f"{year} {f1.grand_prix} Grand Prix")
    prepare_show(directory.parent, config, season_code=f1.code, season_name=name, rebuild=rebuild)
    season = ET.Element("season")
    ET.SubElement(season, "title").text = name
    ET.SubElement(season, "seasonnumber").text = str(int(f1.code))
    ET.SubElement(season, "plot").text = event.get("description", f"Sessions from the {name}, round {int(f1.code[2:])} of the {year} Formula 1 season.")
    write_xml(directory / "season.nfo", season, update=True)
    prepare_artwork(directory, f1, config)


def prepare(video, f1, year, config, *, rebuild=False, replace_content=None):
    prepare_season(video.parent, f1, year, config, rebuild=rebuild)
    event = config.get("events", {}).get(f1.code, {})
    name = event.get("name", f"{year} {f1.grand_prix} Grand Prix")
    session = event.get("sessions", {}).get(f1.event, {})
    from nfo import parse_episode
    season_number, episode, title = parse_episode(video)
    root = ET.Element("episodedetails")
    for tag, value in (("title", session.get("title", title)), ("season", str(season_number)),
                       ("episode", str(episode)), ("year", str(year)),
                       ("plot", session.get("description", f"{f1.event} coverage from the {name}, round {int(f1.code[2:])} of the {year} Formula 1 season."))):
        ET.SubElement(root, tag).text = value
    if session.get("date"):
        ET.SubElement(root, "aired").text = session["date"]
    return write_xml(video.with_suffix(".nfo"), root, update=True, replace_content=replace_content)


def regenerate(directory, config, report):
    """Rebuild destination metadata without needing original source files."""
    from nfo import episode_xml, parse_episode
    from sync import normalized_f1_name
    result = dict(scanned=0, created=0, updated=0, unchanged=0, preserved=0, unparsed=0, errors=0)
    before = {}
    shows = set()

    def failed(error):
        result["errors"] += 1
        report(f"ERROR Metadata regeneration: {error}")

    def remember(path):
        if path not in before:
            before[path] = ("symlink" if path.is_symlink() else
                            path.read_bytes() if os.path.lexists(path) else None)

    for parent, folders, files in os.walk(directory, followlinks=False, onerror=failed):
        folders[:] = sorted(name for name in folders if not (Path(parent) / name).is_symlink())
        parent = Path(parent)
        if "tvshow.nfo" in files:
            try:
                path = parent / "tvshow.nfo"
                if not path.is_symlink() and MARKER in path.read_bytes():
                    remember(path)
                    shows.add(parent)
            except OSError as error:
                failed(error)
        for name in sorted(files):
            video = parent / name
            if video.suffix.lower() not in config.extensions or video.is_symlink() or not video.is_file():
                continue
            result["scanned"] += 1
            parsed = parse_episode(video)
            if parsed is None:
                result["unparsed"] += 1
                report(f"UNPARSED {video}")
                continue
            season, episode, title = parsed
            try:
                remember(video.with_suffix(".nfo"))
                # Exact old CLI output is safe to upgrade; other unmarked NFOs remain authored metadata.
                legacy = episode_xml(*parsed).encode("utf-8")
                code = str(season).zfill(4)
                year = season_year(code)
                f1 = None
                if year is not None and parent.name == f"Season {code}" and parent.parent.is_relative_to(directory):
                    f1, _ = normalized_f1_name(f"Formula1.{year}.Round{int(code[2:])}.{title}{video.suffix}", config)
                if f1 is not None:
                    remember(parent / "season.nfo")
                    remember(parent.parent / "tvshow.nfo")
                    shows.add(parent.parent)
                    prepare(video, f1, year, config.metadata, rebuild=True, replace_content=legacy)
                else:
                    root = ET.Element("episodedetails")
                    for tag, value in (("title", title), ("season", str(season)), ("episode", str(episode))):
                        ET.SubElement(root, tag).text = value
                    write_xml(video.with_suffix(".nfo"), root, update=True, replace_content=legacy)
            except (OSError, ValueError, ET.ParseError) as error:
                failed(f"{video}: {error}")
    for show in sorted(shows):
        try:
            prepare_show(show, config.metadata, rebuild=True)
        except (OSError, ValueError, ET.ParseError) as error:
            failed(f"{show}: {error}")
    for path, original in before.items():
        try:
            if path.is_symlink():
                status = "preserved"
            elif not path.exists():
                continue
            else:
                content = path.read_bytes()
                status = ("created" if original is None else "updated" if content != original else
                          "unchanged" if MARKER in content else "preserved")
            result[status] += 1
            report(f"{status.upper()} {path}")
        except OSError as error:
            failed(f"{path}: {error}")
    return result
